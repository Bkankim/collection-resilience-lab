/**
 * 시각을 읽는 통로를 하나로 모은다.
 *
 * 차단 판정(속도 제한 창, 차단 유지 시간, 세션 수명)이 전부 시각에 의존한다.
 * 각 모듈이 `Date.now()`를 직접 부르면 테스트에서 시간을 밀 수 없고, 그러면
 * "차단이 T초 뒤에 풀린다"를 실제로 T초 기다리는 방법으로만 검증하게 된다.
 * 주입 가능한 함수 하나로 두면 테스트가 시각을 소유한다.
 */

/** 현재 시각을 epoch 밀리초로 돌려준다. */
export type Clock = () => number;

export const systemClock: Clock = () => Date.now();
